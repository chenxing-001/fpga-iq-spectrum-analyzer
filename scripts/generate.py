"""Deterministic coefficient / tone ROM and FFT hierarchy generator (stdlib only)."""
from pathlib import Path
import math
P=Path(__file__).resolve().parents[1]
def put(p,t): (P/p).write_text(t,encoding='utf-8')
for logn in (13,11,9,7,5,3):
 n=1<<logn
 put(f'data/tw_{n}.hex',''.join(f'{min(2047,round(2048*math.cos(2*math.pi*j/n)))&4095:03x}{min(2047,round(2048*math.sin(2*math.pi*j/n)))&4095:03x}\n' for j in range(n//4)))
for logn in (13,11,9,7,5,3):
 n=1<<logn
 put(f'data/sin_tw_{n}.hex',''.join(f'{min(2047,round(2048*math.sin(2*math.pi*j/n)))&4095:03x}\n' for j in range(n//4)))
for logn in (13,11,9,7,5,3):
 n=1<<logn
 vals=[min(2047,round(2048*math.sin(2*math.pi*j/n))) for j in range(n//4)]
 put(f'data/sin_tw_{n}.mif', f'WIDTH=12;\nDEPTH={n//4};\nADDRESS_RADIX=HEX;\nDATA_RADIX=HEX;\nCONTENT BEGIN\n'+''.join(f'{j:X} : {v:03X};\n' for j,v in enumerate(vals))+'END;\n')
put('data/sine.hex',''.join(f'{round(900*math.sin(2*math.pi*j/256))&4095:03x}\n' for j in range(256)))
s='''`timescale 1ns/1ps
// Generated by scripts/generate.py. 8192-point radix-2^2 DIF SDF, 1 sample/clock.
// Input MUST be continuous after first valid. Output is bit-reversed; bin is natural.
module fft8192_stream(input clk,rst_n,vin,input signed [11:0] xr,xi,
 output vout,output signed [11:0] yr,yi,output [12:0] bin,output [31:0] frame);
wire [19:0] v; wire signed [11:0] r[0:19],i[0:19];
assign v[0]=vin;assign r[0]=xr;assign i[0]=xi;
'''
k=0
for logn in (13,11,9,7,5,3):
 for d,rot in ((1<<(logn-1),0),(1<<(logn-2),1)):
  s+=f'sdf_butterfly #(.D({d}),.AW({d.bit_length()-1}),.ROTATE({rot})) b{k}(clk,rst_n,v[{k}],r[{k}],i[{k}],v[{k+1}],r[{k+1}],i[{k+1}]);\n';k+=1
 s+=f'r22_twiddle #(.LOGN({logn}),.ROM_FILE("data/sin_tw_{1<<logn}.hex"),.MIF_FILE("data/sin_tw_{1<<logn}.mif"),.RAM_STYLE("'+('M9K' if logn>=11 else 'logic')+f'")) t{k}(clk,rst_n,v[{k}],r[{k}],i[{k}],v[{k+1}],r[{k+1}],i[{k+1}]);\n';k+=1
s+=f'sdf_butterfly #(.D(1),.AW(0)) last(clk,rst_n,v[{k}],r[{k}],i[{k}],v[{k+1}],r[{k+1}],i[{k+1}]);\n'
s+='''reg [12:0] seq;reg [31:0] fid;
always @(posedge clk or negedge rst_n) if(!rst_n) begin seq<=0;fid<=0;end
else if(v[19]) begin seq<=seq+1'b1;if(seq==8191) fid<=fid+1'b1;end
assign vout=v[19];assign yr=r[19];assign yi=i[19];assign frame=fid;
genvar b;generate for(b=0;b<13;b=b+1) begin: bin_wire assign bin[b]=seq[12-b];end endgenerate
endmodule
'''
put('rtl/fft8192_stream.v',s)
